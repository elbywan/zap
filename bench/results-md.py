#!/usr/bin/env python3
"""Render the benchmark results table and splice it into the README.

Reads the hyperfine JSON outputs written by bench.sh (bench/react-app/*.json)
and the measured versions (bench/versions.txt), then replaces the content
between the <!-- bench-results:start --> and <!-- bench-results:end -->
markers in the README.

Usage:
  results-md.py <README>          splice the table into the README in place
  results-md.py <README> --table  print the table to stdout only
  results-md.py <README> --check  update bench/results.json and print "true"
                                  if the change is material (medians beyond
                                  the per-scenario thresholds, or different
                                  versions), "false" otherwise
"""

import json
import re
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
RESULTS_JSON = BENCH_DIR / "results.json"

# A change is material when a median moves by more than these fractions
# (the cold scenario is network-bound and far noisier) or when the
# measured versions change.
THRESHOLDS = {
    "cold.json": 0.25,
    "only-cache.json": 0.10,
    "without-lockfile.json": 0.10,
    "without-node-modules.json": 0.10,
}

SCENARIOS = [
    ("cold.json", "Without cache, lockfile or node modules"),
    ("only-cache.json", "Without lockfile or node modules"),
    ("without-lockfile.json", "Without lockfile"),
    ("without-node-modules.json", "Without node modules"),
]
TOOLS = ["npm", "yarn", "pnpm", "bun", "zap"]

START = "<!-- bench-results:start -->"
END = "<!-- bench-results:end -->"


def read_versions():
    versions = {}
    for line in (BENCH_DIR / "versions.txt").read_text().splitlines():
        name, _, value = line.partition("=")
        versions[name] = value
    return versions


def tool_of(command):
    # The yarn command is prefixed with "env KEY=value ..." entries.
    for token in command.split():
        if token != "env" and "=" not in token:
            return token.rsplit("/", 1)[-1]
    raise ValueError(f"no executable found in command: {command!r}")


def fmt_seconds(seconds):
    if seconds < 1:
        return f"{seconds * 1000:.0f} ms"
    return f"{seconds:.1f} s"


def collect():
    versions = read_versions()
    medians = {}
    for json_name, _ in SCENARIOS:
        data = json.loads((BENCH_DIR / "react-app" / json_name).read_text())
        by_tool = {tool_of(r["command"]): r["median"] for r in data["results"]}
        medians[json_name] = {tool: by_tool[tool] for tool in TOOLS}
    return versions, medians


def is_material(versions, medians):
    if not RESULTS_JSON.exists():
        return True
    previous = json.loads(RESULTS_JSON.read_text())
    # The date and the workflow run URL ride along with material changes
    # but never trigger one on their own.
    if any(versions.get(name) != previous["versions"].get(name) for name in TOOLS):
        return True
    for json_name, by_tool in medians.items():
        for tool, value in by_tool.items():
            old = previous["medians"][json_name][tool]
            if abs(value - old) / old > THRESHOLDS[json_name]:
                return True
    return False


def build_table(versions, medians):
    labels = [f"{tool} v{versions.get(tool, '?').lstrip('v')}" for tool in TOOLS]

    lines = [f"| Scenario | {' | '.join(labels)} |"]
    lines.append(f"| --- | {' | '.join('---' for _ in TOOLS)} |")
    for json_name, scenario in SCENARIOS:
        values = [medians[json_name][tool] for tool in TOOLS]
        best = min(values)
        cells = [fmt_seconds(v) if v != best else f"**{fmt_seconds(v)}**" for v in values]
        lines.append(f"| {scenario} | {' | '.join(cells)} |")
    lines.append("")
    lines.append(f"Median of 3 runs after 1 warmup, measured on {versions.get('date', '?')}.")
    run = versions.get("run")
    if run:
        lines.append(f"Results generated by [this workflow run]({run}).")
    return "\n".join(lines)


def main():
    readme = Path(sys.argv[1])
    versions, medians = collect()
    if "--table" in sys.argv:
        print(build_table(versions, medians))
        return
    if "--check" in sys.argv:
        material = is_material(versions, medians)
        if material:
            RESULTS_JSON.write_text(
                json.dumps({"versions": versions, "medians": medians}, indent=2) + "\n"
            )
        print(str(material).lower())
        return
    text = readme.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"markers {START}/{END} not found in {readme}")
    readme.write_text(pattern.sub(f"{START}\n\n{build_table(versions, medians)}\n\n{END}", text))


if __name__ == "__main__":
    main()
